-- Копія реальної схеми Supabase (information_schema, 2026-11-08) для перевірки міграції
CREATE TABLE raw_jobs (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id varchar NOT NULL,
  source varchar NOT NULL, content_hash varchar NOT NULL, payload jsonb NOT NULL,
  status varchar DEFAULT 'pending', processed_at timestamptz, ingested_at timestamptz DEFAULT now(),
  CONSTRAINT uq_raw_content_source UNIQUE (source, content_hash));
CREATE TABLE dim_skills (skill_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  canonical_name varchar NOT NULL UNIQUE, category varchar NOT NULL,
  parent_skill_id integer REFERENCES dim_skills, created_at timestamptz DEFAULT now());
CREATE TABLE dim_skill_aliases (alias_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skill_id integer NOT NULL REFERENCES dim_skills, alias varchar NOT NULL UNIQUE);
CREATE TABLE fct_vacancies (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raw_job_id bigint REFERENCES raw_jobs, external_id varchar NOT NULL, source varchar NOT NULL,
  content_hash varchar, region varchar DEFAULT 'Global', country_code varchar, title varchar NOT NULL,
  company varchar, location varchar, salary_min numeric, salary_max numeric, salary_min_usd numeric,
  salary_max_usd numeric, currency varchar, salary_period varchar DEFAULT 'yearly',
  experience_level varchar DEFAULT 'Not Specified', work_model varchar DEFAULT 'Not Specified',
  track varchar DEFAULT 'Other', is_active boolean DEFAULT true, posted_at timestamptz,
  closed_at timestamptz, created_at timestamptz DEFAULT now(),
  CONSTRAINT uq_fct_vacancy UNIQUE (external_id, source));
CREATE TABLE bridge_vacancy_skills (vacancy_id bigint NOT NULL REFERENCES fct_vacancies,
  skill_id integer NOT NULL REFERENCES dim_skills, confidence_score numeric DEFAULT 1.00,
  created_at timestamptz DEFAULT now(), PRIMARY KEY (vacancy_id, skill_id));
CREATE TABLE fct_arxiv_signals (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  arxiv_id varchar NOT NULL UNIQUE, published_date date NOT NULL, title text NOT NULL,
  category varchar NOT NULL, predicted_skill varchar, predicted_role varchar, signal_summary text,
  created_at timestamptz DEFAULT now());

